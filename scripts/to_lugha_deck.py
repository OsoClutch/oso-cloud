#!/usr/bin/env python3
"""Generate one Lugha deck, validate it, and only then write it.

  python scripts/to_lugha_deck.py --lang es --name Spanish --stage survival --level A1
  python scripts/to_lugha_deck.py --lang es ... --install     # copy onto the device

A deck that fails its checks is never written. The reasons are printed and the
exit status is non-zero, so a loop over many languages cannot quietly ship
something broken.

Two safeguards that matter more than they look:

  * A target file whose "source" is not "oso-cloud" is never overwritten. That
    is what stops this from eating Lugha's eleven hand-written Japanese decks.
  * The filename sets the deck id, and Lugha keys a learner's progress on
    "<deck id>::<front>". Renaming a shipped deck orphans its history, so the
    name is derived, never passed in.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import bedrock  # noqa: E402
import guardrails  # noqa: E402
import rag  # noqa: E402

REPO_DECKS = Path(__file__).resolve().parent.parent / "decks"
DEVICE_DECKS = Path.home() / ".roboface" / "decks"


def known_words(code: str, decks_dir: Path) -> list[str]:
    """What earlier stages of this language already taught.

    Passed to the generator so a new deck builds on known vocabulary instead of
    repeating it - the i+1 idea from method-comprehensible-input.
    """
    words: list[str] = []
    if not decks_dir.is_dir():
        return words
    for path in sorted(decks_dir.glob("*.json")):
        try:
            deck = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        if str(deck.get("code") or "")[:2].lower() != code[:2].lower():
            continue
        for card in deck.get("cards") or []:
            front = str(card.get("front") or "").strip()
            if front:
                words.append(front)
    return words


def safe_to_write(target: Path) -> tuple[bool, str]:
    if not target.exists():
        return True, ""
    try:
        existing = json.loads(target.read_text(encoding="utf-8"))
    except Exception:
        return False, f"{target} exists and is not readable JSON; refusing"
    if existing.get("source") != "oso-cloud":
        return False, (f"{target} was not generated by oso-cloud "
                       f"(source={existing.get('source')!r}); refusing to "
                       "overwrite a hand-written deck")
    return True, ""


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--lang", required=True, help="two-letter code, e.g. es")
    p.add_argument("--name", help="language name for the screen (default: code)")
    p.add_argument("--stage", required=True, choices=guardrails.STAGES)
    p.add_argument("--level", required=True,
                   choices=guardrails.CEFR + guardrails.JLPT)
    p.add_argument("--out", help="write here instead of decks/<code>_<stage>.json")
    p.add_argument("--install", action="store_true",
                   help=f"also copy into {DEVICE_DECKS}")
    p.add_argument("--k", type=int, default=rag.TOP_K)
    args = p.parse_args()

    code = args.lang.lower()
    name = args.name or code.upper()

    index = rag.load_index()
    query = (f"{args.level} {name} {args.stage} stage: which words and phrases "
             f"to teach, and the deck format")
    hits = rag.search(query, k=args.k, index=index)

    print(f"backend  : {index['backend']}")
    print(f"retrieved: {len(hits)} passage(s) above {rag.min_score()}")
    for h in hits:
        print(f"   {h.score:>7.4f}  {h.doc_id:<30} {h.heading}")

    if not hits:
        print("\nFAIL nothing retrieved above the score floor; refusing to generate")
        return 1

    known = known_words(code, DEVICE_DECKS if DEVICE_DECKS.is_dir() else REPO_DECKS)
    if known:
        print(f"known    : {len(known)} front(s) already taught in {code}")

    candidate = bedrock.generate_deck(name, code, args.stage, args.level,
                                      hits, known)
    report = guardrails.check_deck(candidate, code, args.stage, args.level)

    print(f"\nchecks   : {report.summary()}")
    for e in report.errors:
        print(f"   ERROR {e}")
    for w in report.warnings:
        print(f"   warn  {w}")

    if not report.ok:
        print("\nnot written.")
        return 1

    target = Path(args.out) if args.out else REPO_DECKS / f"{code}_{args.stage}.json"
    target.parent.mkdir(parents=True, exist_ok=True)

    allowed, why = safe_to_write(target)
    if not allowed:
        print(f"\nFAIL {why}")
        return 1

    target.write_text(json.dumps(candidate, ensure_ascii=False, indent=1),
                      encoding="utf-8")
    print(f"\nwritten  : {target}  ({len(candidate['cards'])} cards, "
          f"reviewed={candidate['reviewed']})")

    if args.install:
        DEVICE_DECKS.mkdir(parents=True, exist_ok=True)
        device_target = DEVICE_DECKS / target.name
        allowed, why = safe_to_write(device_target)
        if not allowed:
            print(f"FAIL {why}")
            return 1
        shutil.copy2(target, device_target)
        print(f"installed: {device_target}")
        print("Progress lives in ~/.roboface/lugha_state.json and is untouched.")

    if not report.warnings:
        return 0
    print("\nShipped with warnings. reviewed=false until a speaker checks it.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
